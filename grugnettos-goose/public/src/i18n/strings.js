export function translator(language = 'it') {
  const strings = STRINGS[language] ?? STRINGS.it;
  return (key, vars = {}) => {
    let value = strings[key] ?? key;
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  };
}
