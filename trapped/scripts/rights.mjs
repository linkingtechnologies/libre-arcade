#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-only
// File-by-file rights register for everything under public/ (the distributable tree).
//   node scripts/rights.mjs           regenerate specs/RIGHTS-REGISTER.md and specs/asset-manifest.json
//   node scripts/rights.mjs --check   fail if a file has no rule, a rule is not cleared, or the
//                                     committed register is out of date (used by `npm run build`)
// Rules live in specs/rights-rules.json. A rule whose status is not "ok" or "ok-with-note"
// blocks the build, so an asset with unresolved redistribution rights cannot ship.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const CLEARED = new Set(['ok', 'ok-with-note']);

const { game, rules } = JSON.parse(await readFile(`${root}specs/rights-rules.json`, 'utf8'));

async function walk(dir, base = '') {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...await walk(`${dir}/${e.name}`, rel));
    else out.push(rel);
  }
  return out.sort();
}

const files = await walk(`${root}public`);
const entries = [];
const problems = [];
for (const f of files) {
  const path = `public/${f}`;
  const rule = rules.find((r) => new RegExp(r.match).test(path));
  const sha256 = createHash('sha256').update(await readFile(`${root}${path}`)).digest('hex');
  if (!rule) { problems.push(`${path}: no rights rule`); entries.push({ path, sha256, status: 'unresolved' }); continue; }
  if (!CLEARED.has(rule.status)) problems.push(`${path}: status "${rule.status}"`);
  entries.push({ path, sha256, category: rule.category, author: rule.author, source: rule.source, license: rule.license,
    status: rule.status, replaced: rule.replaces || 'no', note: rule.note || '' });
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const md = [
  `# Rights register: ${game}`, '',
  'Generated by `node scripts/rights.mjs` from `specs/rights-rules.json`. Do not edit by hand.',
  'Status `ok` = cleared; `ok-with-note` = cleared with an open point described in the note.', '',
  '| File | Category | Author | Source | License | SHA-256 | Status | Replaces historical asset | Note |',
  '|---|---|---|---|---|---|---|---|---|',
  ...entries.map((e) => `| \`${e.path}\` | ${esc(e.category)} | ${esc(e.author)} | ${esc(e.source)} | ${esc(e.license)} | \`${e.sha256.slice(0, 16)}…\` | ${e.status} | ${esc(e.replaced)} | ${esc(e.note)} |`),
  '',
].join('\n');
const manifest = JSON.stringify({ game, files: entries }, null, 2) + '\n';

if (check) {
  if (problems.length) { console.error('Rights check failed:\n' + problems.join('\n')); process.exit(1); }
  const cur = await readFile(`${root}specs/RIGHTS-REGISTER.md`, 'utf8').catch(() => '');
  const curM = await readFile(`${root}specs/asset-manifest.json`, 'utf8').catch(() => '');
  if (cur !== md || curM !== manifest) { console.error('Rights register is out of date: run `node scripts/rights.mjs`'); process.exit(1); }
  console.log(`Rights check passed: ${entries.length} files cleared.`);
} else {
  await writeFile(`${root}specs/RIGHTS-REGISTER.md`, md);
  await writeFile(`${root}specs/asset-manifest.json`, manifest);
  console.log(`Wrote register for ${entries.length} files` + (problems.length ? `; ${problems.length} problem(s):\n${problems.join('\n')}` : ''));
}
