'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),a=require('../public/js/audio.js');
const calls={play:0,pause:0};
const media={paused:true,volume:0,loop:false,preload:'none',play(){calls.play++;this.paused=false;return Promise.resolve();},pause(){calls.pause++;this.paused=true;}};
const sound=a.create(null,media);
assert.equal(sound.music,true,'soundtrack enabled by default after game launch');
assert.equal(media.loop,true);assert.equal(media.volume,.65);
sound.updateMusic(true);assert.equal(calls.play,1);assert.equal(media.paused,false);
sound.updateMusic(true);assert.equal(calls.play,1,'no redundant play each animation frame');
sound.setMuted(true);sound.updateMusic(true);assert.equal(media.paused,false,'muting effects must not silence soundtrack');
sound.setMusicVolume(.4);assert.equal(media.volume,.4);
sound.updateMusic(false);assert.equal(media.paused,true);assert.equal(calls.pause,1);
sound.updateMusic(true);assert.equal(calls.play,2,'resumes after explicit game start');
sound.setMusic(false);assert.equal(media.paused,true);
sound.updateMusic(true);assert.equal(calls.play,2,'off means off');
sound.setMusic(true);sound.updateMusic(true);assert.equal(calls.play,3);
sound.close();assert.equal(media.paused,true);
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
for(const source of ['assets/music/comet-loop.ogg','assets/music/comet-loop.mp3'])assert(html.includes(source));
for(const file of ['ogg','mp3'])assert(fs.statSync(path.join(root,'public/assets/music/comet-loop.'+file)).size>30000);
assert(html.includes('id="musicVolume"')&&html.includes('id="musicTrack"'));
console.log('PASS M13.3: real CC0 media loop, play/pause/resume, independent effects mute, music level and audio formats');
