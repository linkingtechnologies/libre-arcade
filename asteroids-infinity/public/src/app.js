function frame(now){
  if(last===0)last=now;const elapsed=Math.max(0,(now-last)/1000);last=now;
  fpsFrames++;fpsTime+=elapsed;if(fpsTime>=1){fpsValue=Math.round(fpsFrames/fpsTime);fpsFrames=0;fpsTime=0;}
  if(machine.screen==='play'){
    // Original tick(100) yields one measured dt per frame, not a fixed-step
    // catch-up loop. Browser tab suspension is intentionally NOT simulated.
    const dt=simClock.advance(now/1000);
    if(dt!==null){
      const previousShip=state.ship,previousBullets=new Set(state.bullets),
        previousDestroyed=state.destroyed,previousSaucers=state.spawnedSaucers,previousWave=state.wave,
        command=controls.get();
      step(state,command,dt);
      if(state.bullets.some(b=>b.creator===previousShip&&!previousBullets.has(b)))sound.play('shoot');
      if(previousShip&&state.lostShips>0&&state.ship!==previousShip)sound.play('ship');
      else if(state.destroyed>previousDestroyed)sound.play('hit');
      if(state.spawnedSaucers>previousSaucers)sound.play('saucer');
      if(state.wave>previousWave)sound.play('wave');
      if(previousShip&&command.up)sound.play('thrust');
      if(previousShip&&command.shield)sound.play('shield');
      if(state.mode==='gameover')finishGame();}
  }
  render(ctx,state,{labels:machine.screen==='play',language:locale});
  const meter=document.querySelector('#fps-meter');if(!meter.hidden)meter.textContent=`FPS ${fpsValue}`;
  requestAnimationFrame(frame);
}
