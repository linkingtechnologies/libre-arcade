function chooseItem(index=machine.selected){
  if(machine.binding)return;
  const current=machine.screen;
  if(!MENU_ITEMS[current])return;
  machine.selected=index;
  if(current==='gameover'){advanceFromGameOver();return;}
  if(current==='name'){submitName();return;}
  const item=machine.choose();notice='';
  if(current==='menu'&&item==='play'){startGame();return;}
  if(current==='options'){
    if(item==='fullscreen'){
      const request=document.fullscreenElement?document.exitFullscreen?.bind(document):document.documentElement.requestFullscreen?.bind(document.documentElement);
      if(!request)notice=msg().fullFail;
      else try{Promise.resolve(request()).catch(()=>{notice=msg().fullFail;refresh();});}catch{notice=msg().fullFail;}
    }else if(item==='fps')showFPS=!showFPS;
    else if(item==='volume')toggleSound();
  }
  if(machine.binding)controls.clear();
  refresh();
}
