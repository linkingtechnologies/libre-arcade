      buf[off]=0;
      toggle^=1;
      if(toggle){const b=[off];if(stored!==null){b.push(stored);stored=null;}batches.push(b);}else stored=off;
      const next=code^1;
      for(const n of [off-1,off+1,off-16,off+16]){
        if(n>=0&&n<256&&buf[n]!==0){buf[n]=next;added=true;}
      }
