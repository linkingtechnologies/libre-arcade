#!/usr/bin/env python3
"""Rebuild ConnectLab's categorical Naive Bayes counts from UCI Connect-4."""
from __future__ import annotations
import csv, gzip, json, pathlib, subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reference/uci-connect-4/connect-4.data.Z"
OUTPUT = ROOT / "public/src/players/uci-naive-bayes-knowledge.js"
CLASSES = ("win", "loss", "draw")
VALUES = ("x", "o", "b")

raw = subprocess.check_output(["uncompress", "-c", str(SOURCE)], text=True)
rows = list(csv.reader(raw.splitlines()))
class_counts = [0] * 3
counts = [[0] * (42 * 3) for _ in CLASSES]
for row in rows:
    features, label = row[:42], row[42]
    k = CLASSES.index(label)
    class_counts[k] += 1
    for i, value in enumerate(features):
        counts[k][i * 3 + VALUES.index(value)] += 1

payload = {"classes": CLASSES, "values": VALUES, "rows": len(rows),
           "classCounts": class_counts, "counts": counts}
OUTPUT.write_text(
    "// Generated by tools/train-uci-naive-bayes.py from UCI Connect-4.\n"
    "export const UCI_NB = " + json.dumps(payload, separators=(",", ":")) + ";\n",
    encoding="utf-8", newline="\n")
print(f"wrote {OUTPUT.relative_to(ROOT)} from {len(rows)} rows; classes={class_counts}")
