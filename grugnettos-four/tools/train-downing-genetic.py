#!/usr/bin/env python3
"""Reproduce Jacob Downing's population training with an explicit seed."""
import json
import random
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL = ROOT / "reference" / "jacob-downing-genetic-connect-four" / "original"
sys.path.insert(0, str(ORIGINAL))
from modules import league  # noqa: E402


def main():
    generations = int(sys.argv[1]) if len(sys.argv) > 1 else 100
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "public/src/players/jacob-downing-genetic-weights.js"
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 20190415
    np.random.seed(seed)
    random.seed(seed)
    league.generate_pop()
    league.play_season()
    for generation in range(generations):
        league.repop_from(league.gather_top())
        league.play_season()
        if (generation + 1) % 10 == 0:
            print(f"generation {generation + 1}/{generations}", flush=True)
    best = league.gather_top(n=1, nmax=1)[0]
    best_index = league.population.index(best)
    weights = best.export()
    metadata = {
        "sourceCommit": "0b0f78f20c807f25fcfa027a02e407bd0b96b64c",
        "seed": seed,
        "generations": generations,
        "population": league.POP_SIZE,
        "network": list(league.NET_STRUCT),
        "mutatedNodes": league.MUTATED_NODES,
        "finalWins": league.standings[best_index][0],
        "finalLosses": league.standings[best_index][1],
    }
    output.write_text(
        "/* Generated by tools/train-downing-genetic.py from the preserved MIT source. */\n"
        f"export const downingGeneticMetadata = {json.dumps(metadata, separators=(',', ':'))};\n"
        f"export const downingGeneticWeights = {json.dumps(weights, separators=(',', ':'))};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(json.dumps(metadata, sort_keys=True))


if __name__ == "__main__":
    main()
