const WIDTH = 7, HEIGHT = 6;
const ALPHA = 0.1, GAMMA = 0.6, EPSILON_MIN = 0.01, EPSILON_DECAY = 0.995;
const EPISODES_PER_SEAT = Number(process.argv[2] ?? 10000);
const SEED = Number(process.argv[3] ?? 20200521) >>> 0;
