// Regenerates public/assets/PROVENANCE.json, the machine-readable inventory of everything that
// ships: path, SHA-256, kind, author, source, licence and the evidence for it. The facts that
// cannot be read off a file (who made the music, under what licence, where it came from) are
// declared in EVIDENCE below, and the licence of each own file is the SPDX tag it carries.
// scripts/gate.mjs then refuses to publish unless this file is complete and current.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pub = join(root, "public");
export const OUT = join(pub, "assets/PROVENANCE.json");

// Facts that need a human source. Anything shipped that is neither here nor an SPDX-tagged text
// file of ours is unverified, and the gate fails.
export const EVIDENCE = {
  "assets/music/trouble-in-the-garden.ogg": {
    kind: "music",
    title: "Trouble in the Garden",
    author: "Augmentality (Brandon Morris); submitted to OpenGameArt by HaelDB",
    source: "https://opengameart.org/content/trouble-in-the-garden (file \"trouble in the garden.ogg\", 2,468,541 bytes, downloaded 2026-11-22)",
    license: "CC0-1.0",
    evidence: "The OpenGameArt page, read 2026-11-22, lists License(s): OGA-BY 3.0 and CC0 (a dual licence: the recipient may choose either). This file is used under CC0. It is the original, not the low-quality transcode the 2012 game shipped.",
    verified: true,
  },
  "LICENSE": { kind: "licence-text", author: "Free Software Foundation", source: "https://www.gnu.org/licenses/gpl-3.0.txt", license: "GPL-3.0-or-later (text of the licence itself)", evidence: "Identical to the LICENSE of the other games in this collection.", verified: true },
  "THIRD_PARTY_NOTICES.md": { kind: "notices", author: "this project", source: "this repository", license: "GPL-3.0-or-later", evidence: "Quotes the licences of the third-party code and media the game carries.", verified: true },
  "CREDITS.md": { kind: "notices", author: "this project", source: "this repository", license: "GPL-3.0-or-later", evidence: "Attribution of the original authors.", verified: true },
};

const TEXT_EXT = new Set([".js", ".mjs", ".html", ".css"]);
const ALLOWED_SPDX = new Set(["GPL-3.0-or-later", "GPL-3.0-or-later AND MIT", "GPL-3.0-or-later AND MIT AND CC-BY-3.0"]);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

export function build() {
  const files = [];
  for (const abs of walk(pub)) {
    const rel = relative(pub, abs).split(sep).join("/");
    if (rel === "assets/PROVENANCE.json") continue;
    const buf = readFileSync(abs);
    const entry = { path: rel, bytes: buf.length, sha256: createHash("sha256").update(buf).digest("hex") };
    const ext = rel.slice(rel.lastIndexOf("."));
    if (EVIDENCE[rel]) Object.assign(entry, EVIDENCE[rel]);
    else if (TEXT_EXT.has(ext)) {
      const m = buf.toString("utf8").slice(0, 600).match(/SPDX-License-Identifier:\s*([^\r\n]*?)\s*(?:-->|\*\/)?\s*[\r\n]/);
      const spdx = m ? m[1].trim() : null;
      Object.assign(entry, {
        kind: ext === ".css" ? "style" : ext === ".html" ? "markup" : "code",
        author: "Umberto Bresciani (this restoration)" + (spdx && spdx.includes("MIT") ? "; logic ported from Petar Petrov's MIT-licensed original" : ""),
        source: "this repository",
        license: spdx,
        evidence: "SPDX tag in the file header",
        verified: !!spdx && ALLOWED_SPDX.has(spdx),
      });
    } else {
      Object.assign(entry, { kind: "unknown", verified: false, license: null, evidence: "no rule covers this file" });
    }
    files.push(entry);
  }
  return {
    schema: 1,
    game: "Raging Gardens",
    note: "Everything under public/ is listed here with its SHA-256. The pictures are generated by src/art.js and the sound effects by src/audio.js at run time, so they are code, covered by those files' entries. The original artwork (Stremena Tuzsuzova) and the original sound-effect files are NOT shipped: see reference/SOURCES.json (keep: excluded) and docs/ASSET_LICENSE_INVENTORY.md.",
    files,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const manifest = build();
  writeFileSync(OUT, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`wrote ${relative(root, OUT)}: ${manifest.files.length} files, ${manifest.files.filter((f) => !f.verified).length} unverified`);
}
