#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Dev tooling. Writes ASSET-PROVENANCE.md: one row per shipped file with its
// SHA-256, origin and licence, from SOURCE-MANIFEST.json.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const m = JSON.parse(readFileSync(`${root}SOURCE-MANIFEST.json`, "utf8"));
const LICENCE = [
  [/^assets\/sounds\/happy\./, "CC BY 3.0 (rezoner)", "A (mp3 byte-matched) / B (ogg)"],
  [/^assets\/sounds\/air\.wav/, "CC0 1.0 (remaxim)", "B"],
  [/^assets\/sounds\/water\.wav/, "CC BY 3.0 (kurt)", "B"],
  [/^assets\/sounds\/earth\.wav/, "CC BY 3.0 (qubodup)", "B"],
  [/^assets\/sounds\/(fire|pickup)\.wav/, "CC BY-SA 3.0 / GPL 3.0 (p0ss)", "B"],
  [/^assets\/sounds\/jump\.wav/, "GPL-3.0-or-later (synthesized here)", "own work"],
  [/^assets\/(sprites|tilesets)\//, "CC0 1.0 (Kenney)", "B"],
  [/^assets\/images\//, "MIT / CC0 (author composite of Kenney tiles)", "B (assumed)"],
  [/^assets\/tilemaps\//, "MIT (Zaven Muradyan)", "A (repository licence)"],
  [/^fonts\/Jersey10/, "SIL OFL 1.1 (Soft Type Project Authors)", "A (OFL.txt shipped)"],
  [/^fonts\/OFL/, "licence text", "-"],
  [/^js\/phaser\.js/, "MIT (Photon Storm, Mat Groves, Ivan Kuckir)", "A (headers)"],
  [/^js\/game\.js/, "MIT (Zaven Muradyan)", "A"],
  [/^(index\.html|css\/|js\/(arcade|i18n))/, "MIT (integration layer)", "own work"],
  [/^(LICENSE|CREDITS)/, "-", "-"],
];
let out = `# Asset provenance

Generated by \`tools/asset-table.mjs\` from \`SOURCE-MANIFEST.json\`. Evidence levels: **A** matched/verified, **B** declared upstream and not byte-matched (see \`LICENSE-AUDIT.md\`).
Upstream commit \`${m.upstream.commit}\`.

| Shipped file (\`public/\`) | SHA-256 | Origin | Licence | Evidence |
|---|---|---|---|---|
`;
for (const [f, v] of Object.entries(m.shippedFiles)) {
  const [, lic, ev] = LICENCE.find(([re]) => re.test(f)) ?? [null, "UNCLEARED", "none"];
  const origin = v.kind === "upstream-verbatim" ? `upstream \`${v.reference}\`` : v.kind;
  out += `| \`${f}\` | \`${v.sha256.slice(0, 16)}…\` | ${origin} | ${lic} | ${ev} |\n`;
}
out += `
## Withheld from redistribution

| Upstream file | SHA-256 (full) | Why |
|---|---|---|
`;
for (const [f, v] of Object.entries(m.withheldFromReference)) out += `| \`${f}\` | \`${v.sha256}\` | ${v.reason} |\n`;
out += "\nUpstream files kept only in `reference/` and not shipped: `enemies_spritesheet.png`, `hud_spritesheet.*`, `p2_spritesheet.png`, `p3_spritesheet.png`, the `.tmx` sources, `build/`, `deps/phaser.min.js`.\n";
writeFileSync(`${root}ASSET-PROVENANCE.md`, out);
console.log("wrote ASSET-PROVENANCE.md");
