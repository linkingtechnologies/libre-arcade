function norm(s){return String(s).normalize('NFD').replace(/[\u0300-\u036f]/g,'').toUpperCase();}
export function dotTextWidth(text,scale=2,gap=1){const t=norm(text);return t.length?((5*scale+gap)*t.length-gap):0;}
export function drawDotText(ctx,text,x,y,{scale=2,gap=1,color='#fff',align='left',alpha=1}={}){
  const t=norm(text);const w=dotTextWidth(t,scale,gap);let sx=x;
  if(align==='center')sx-=w/2; else if(align==='right')sx-=w;
  ctx.save();ctx.fillStyle=color;ctx.globalAlpha*=alpha;
  const r=Math.max(.65,scale*.42);
  for(let ci=0;ci<t.length;ci++){
    const rows=G[t[ci]]||G['?'];const ox=sx+ci*(5*scale+gap);
    for(let yy=0;yy<7;yy++)for(let xx=0;xx<5;xx++)if(rows[yy][xx]==='1'){
      const cx=ox+xx*scale+scale/2,cy=y+yy*scale+scale/2;
      ctx.beginPath();ctx.arc(cx,cy,r,0,Math.PI*2);ctx.fill();
    }
  }
  ctx.restore();return w;
}
